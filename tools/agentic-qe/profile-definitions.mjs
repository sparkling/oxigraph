function cargo(args, expectedPassedTests, evidencePackages, policy = {}) {
  return [
    "cargo",
    ["test", "--locked", ...args],
    {
      minimumPassedTests: expectedPassedTests,
      expectedPassedTests,
      timeoutMs: 300_000,
      evidencePackages,
      ...policy,
    },
  ];
}

