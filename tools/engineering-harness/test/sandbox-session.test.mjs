test("one quota-bound namespace preserves build state across every evaluator", { timeout: 180_000 }, async () => {
  const root = await mkdtemp(join(tmpdir(), "oxigraph-session-test-"));
  try {
    const workspace = await createFixture(root);
    const output = join(root, "structural-result.json");
    const descriptor = await open(output, "wx", 0o600);
    await descriptor.close();
    const maxDiskBytes = 512 * mebibyte;
    const structural = sandboxSessionArguments({
      workspace,
      outputFile: output,
      maxDiskBytes,
      cargoBuildJobs: 2,
    });
    const stateMount = structural.indexOf("--tmpfs");
    assert.equal(structural[stateMount - 2], "--size");
    assert.equal(structural[stateMount - 1], String(maxDiskBytes));
    assert.equal(structural[stateMount + 1], "/state");
    assert.ok(structural.includes("--unshare-net"));
    assert.ok(structural.includes("--unshare-pid"));
    assert.ok(structural.includes("--clearenv"));
    const incrementalIndex = structural.indexOf("CARGO_INCREMENTAL");
    assert.ok(incrementalIndex > 0);
    assert.equal(structural[incrementalIndex - 1], "--setenv");
    assert.equal(structural[incrementalIndex + 1], "0");
    const testDebugIndex = structural.indexOf("CARGO_PROFILE_TEST_DEBUG");
    assert.ok(testDebugIndex > 0);
    assert.equal(structural[testDebugIndex - 1], "--setenv");
    assert.equal(structural[testDebugIndex + 1], "0");
    assert.ok(structural.includes("--remount-ro"));
    assert.notEqual(
      structural.findIndex(
        (value, index) =>
          value === "--dev" &&
          structural[index + 1] === "/dev" &&
          structural[index + 2] === "--remount-ro" &&
          structural[index + 3] === "/dev",
      ),
      -1,
    );
    const workspaceIndex = structural.indexOf("/workspace");
    assert.equal(structural[workspaceIndex - 2], "--ro-bind");
    assert.ok(!structural.includes("/target"));

    const report = await runSandboxVerificationSession({
      workspace,
      commands: commandPlan(),
      maxTotalWallMs: 150_000,
      maxResidentBytes: 2 * 1024 * mebibyte,
      maxDiskBytes,
      cargoBuildJobs: 2,
      maxBuildOutputBytes: mebibyte,
      maxTestOutputBytesPerCommand: mebibyte,
    });
    assert.equal(report.session.status, "completed", report.session.error);
    assert.equal(
      report.session.stage,
      "complete",
      report.session.commands.map(({ stderr, stdout }) => `${stdout}\n${stderr}`).join("\n"),
    );
    assert.deepEqual(
      report.session.commands.map(({ name }) => name),
      ["format", "build", "public", "independent", "regression"],
    );
    assert.ok(
      report.session.commands.every(
        ({ disposition, exitCode }) => disposition === "completed" && exitCode === 0,
      ),
    );
    assert.ok(
      report.session.commands.every(
        ({ diagnostic }) =>
          diagnostic.primaryClass === null &&
          diagnostic.rustcCodes.length === 0 &&
          diagnostic.childTermination === null &&
          diagnostic.ioErrno === null,
      ),
    );
    assert.deepEqual(
      new Set(report.session.artifacts.map(({ name }) => name.split("-")[0])),
      new Set(["public", "independent", "regression"]),
    );
    assert.ok(report.session.artifacts.every(({ sha256 }) => /^[a-f0-9]{64}$/.test(sha256)));
    assert.ok(report.session.stateBytes > 0 && report.session.stateBytes <= maxDiskBytes);
    assert.equal(report.invocation.network, "isolated");
    assert.equal(report.invocation.workspace, "read-only");
    assert.equal(report.invocation.state, "single-quota-tmpfs");
    await assert.rejects(access(join(workspace, "target")));
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

