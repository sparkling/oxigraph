async function processRecordsMatching(needles) {
  const records = [];
  for (const entry of await readdir("/proc", { withFileTypes: true })) {
    if (!entry.isDirectory() || !/^\d+$/.test(entry.name)) continue;
    try {
      const commandLine = (await readFile(`/proc/${entry.name}/cmdline`))
        .toString("utf8")
        .replaceAll("\0", " ");
      if (!needles.some((needle) => commandLine.includes(needle))) continue;
      const stat = (await readFile(`/proc/${entry.name}/stat`, "utf8")).trim();
      const close = stat.lastIndexOf(")");
      const fields = stat.slice(close + 2).split(" ");
      records.push(
        Object.freeze({
          pid: Number(entry.name),
          startTime: fields[19],
          commandLine,
        }),
      );
    } catch (error) {
      if (!["ENOENT", "ESRCH"].includes(error.code)) throw error;
    }
  }
  return records;
}

async function waitForProcesses(needles, deadlineMs, earlyFailure = () => null) {
  const deadline = Date.now() + deadlineMs;
  for (;;) {
    const failure = earlyFailure();
    if (failure !== null) throw failure;
    const records = await processRecordsMatching(needles);
    if (records.length > 0) return records;
    if (Date.now() >= deadline) {
      throw new Error(`timed out waiting for process evidence: ${needles.join(", ")}`);
    }
    await delay(25);
  }
}

async function waitForNoProcesses(needles, deadlineMs) {
  const deadline = Date.now() + deadlineMs;
  for (;;) {
    const records = await processRecordsMatching(needles);
    if (records.length === 0) return;
    if (Date.now() >= deadline) {
      throw new Error(`verifier process tree survived cancellation: ${records.map(({ commandLine }) => commandLine).join(" | ")}`);
    }
    await delay(25);
  }
}

async function originalProcessIsGone(record) {
  try {
    const stat = (await readFile(`/proc/${record.pid}/stat`, "utf8")).trim();
    const close = stat.lastIndexOf(")");
    const fields = stat.slice(close + 2).split(" ");
    return fields[19] !== record.startTime;
  } catch (error) {
    if (["ENOENT", "ESRCH"].includes(error.code)) return true;
    throw error;
  }
}

