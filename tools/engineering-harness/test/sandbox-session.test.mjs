test("production aggregate verifier cancellation reaps an escaped Cargo tree and cleans private state", { timeout: 20_000 }, async () => {
  const root = await mkdtemp(join(tmpdir(), "oxigraph-session-cancel-test-"));
  const token = `oxigraph-cancel-${process.pid}-${randomUUID()}`;
  let privateOutputRoot;
  let earlyFailure = null;
  try {
    const workspace = await createSlowFixture(root, token);
    const controller = new AbortController();
    const running = runSandboxVerificationSession({
      workspace,
      commands: slowCommandPlan(),
      maxTotalWallMs: 15_000,
      maxResidentBytes: 2 * 1024 * mebibyte,
      maxDiskBytes: 256 * mebibyte,
      cargoBuildJobs: 2,
      maxBuildOutputBytes: mebibyte,
      maxTestOutputBytesPerCommand: mebibyte,
      signal: controller.signal,
      processRunner: async (request) => {
        const resultDestination = request.args.indexOf("/result/session.json");
        assert.ok(resultDestination > 0, "production bwrap invocation must bind one result file");
        privateOutputRoot = dirname(request.args[resultDestination - 1]);
        return runBoundedProcess(request);
      },
    });
    running.catch((error) => {
      earlyFailure = error;
    });

    const live = await waitForProcesses(
      [token],
      8_000,
      () => earlyFailure,
    );
    assert.ok(privateOutputRoot?.startsWith(join(tmpdir(), "oxigraph-verifier-session-")));
    const namespaceProcesses = await processRecordsMatching([privateOutputRoot]);
    assert.ok(namespaceProcesses.length > 0, "systemd/bwrap invocation was not observable");
    controller.abort();

    let cancellation;
    try {
      await running;
      assert.fail("cancelled verifier unexpectedly completed");
    } catch (error) {
      cancellation = error;
    }
    assert.equal(cancellation.outcome.disposition, "cancelled");
    assert.equal(cancellation.outcome.terminationErrors.length, 0);

    await waitForNoProcesses([token, privateOutputRoot], 5_000);
    for (const record of [...live, ...namespaceProcesses]) {
      assert.equal(await originalProcessIsGone(record), true, `PID ${record.pid} was not reaped`);
    }
    await assert.rejects(access(privateOutputRoot));
    await assert.rejects(access(join(workspace, "target")));
    await assert.rejects(access(join(root, "state")));
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
