function entryTask(parentRole, entry) {
  let role = null;
  let kind = null;
  if (entry.kind === "REGULAR") {
    kind = "REGULAR_FILE";
    role = parentRole;
  } else if (entry.kind === "DIRECTORY") {
    kind = "DIRECTORY";
    if (parentRole === "STATE_ROOT") {
      if (entry.name === "lifetimes") role = "LIFETIMES";
      else if (entry.name === "staging") role = "STAGING";
      else if (entry.name === "active") role = "ACTIVE";
      else if (entry.name === "closed") role = "CLOSED";
      else if (entry.name === "recovered") role = "RECOVERED";
      else if (entry.name === "quarantined") role = "QUARANTINED";
    } else if (parentRole === "LIFETIMES") {
      role = "LIFETIME_SEGMENT";
    } else if (
      parentRole === "STAGING" ||
      parentRole === "ACTIVE" ||
      parentRole === "CLOSED" ||
      parentRole === "RECOVERED" ||
      parentRole === "QUARANTINED"
    ) {
      role = "GENERATION";
    } else if (parentRole === "GENERATION" && entry.name === "normal") {
      role = "NORMAL_JOURNAL";
    } else if (parentRole === "GENERATION" && entry.name === "recovery") {
      role = "RECOVERY_JOURNAL";
    } else if (parentRole === "RECOVERY_JOURNAL") {
      role = "RECOVERY_ATTEMPT";
    }
  }
  if (kind === null || role === null) failBinding();
  return nullRecord([
    ["kind", kind],
    ["role", role],
    ["parentRole", parentRole],
    ["name", entry.name],
  ]);
}

function traversalExpected(traversal) {
  const frames = traversal;
  const top = lastValue(frames);
  if (top === undefined) failBinding();
  if (top.inventoried !== true) {
    return nullRecord([
      ["operation", "INVENTORY"],
      ["inventoryKind", "DIRECTORY"],
      ["role", top.role],
      ["parentRole", top.parentRole],
      ["name", top.name],
      ["handle", null],
    ]);
  }
  if (top.tasks.length > 0) {
    const task = firstValue(top.tasks);
    return nullRecord([
      ["operation", "INVENTORY"],
      ["inventoryKind", task.kind],
      ["role", task.role],
      ["parentRole", task.parentRole],
      ["name", task.name],
      ["handle", null],
    ]);
  }
  if (top.role === "STATE_ROOT") return null;
  return nullRecord([
    ["operation", "RELEASE_DIRECTORY"],
    ["inventoryKind", "NONE"],
    ["role", top.role],
    ["parentRole", null],
    ["name", null],
    ["handle", top.handle],
  ]);
}

function validateTraversalRequest(metadata, request) {
  const expected = traversalExpected(metadata.traversal);
  if (expected === null || request.operation !== expected.operation) failBinding();
  if (request.operation === "INVENTORY") {
    if (
      request.inventoryKind !== expected.inventoryKind ||
      request.nameA !== expected.name ||
      request.directoryRoleA !== expected.parentRole
    ) {
      failBinding();
    }
    if (
      expected.inventoryKind === "DIRECTORY" &&
      request.inventoryDirectoryRole !== expected.role
    ) {
      failBinding();
    }
    if (
      expected.inventoryKind === "REGULAR_FILE" &&
      request.inventoryDirectoryRole !== null
    ) {
      failBinding();
    }
  } else if (
    request.directoryRoleA !== expected.role ||
    request.directoryHandleSha256A !== expected.handle
  ) {
    failBinding();
  }
}

function advanceTraversal(traversal, receipt) {
  const frames = [];
  for (const frame of traversal) frames.push(frame);
  const top = frames.pop();
  if (top === undefined) failBinding();
  if (receipt.request.operation === "RELEASE_DIRECTORY") {
    return frames;
  }
  if (receipt.request.operation !== "INVENTORY") failBinding();
  if (receipt.inventories.length !== 1) failBinding();
  const inventory = firstValue(receipt.inventories);
  if (receipt.request.inventoryKind === "REGULAR_FILE") {
    const remaining = [];
    for (const task of top.tasks) remaining.push(task);
    remaining.shift();
    frames.push(
      nullRecord([
        ["role", top.role],
        ["parentRole", top.parentRole],
        ["name", top.name],
        ["handle", top.handle],
        ["inventoried", true],
        ["tasks", remaining],
      ]),
    );
    return frames;
  }
  const tasks = [];
  if (receipt.request.inventoryDirectoryRole === "STATE_ROOT") {
    const rootOrder = ["lifetimes", "staging", "active", "closed", "recovered", "quarantined"];
    for (const name of rootOrder) {
      for (const entry of inventory.entries) {
        if (entry.name === name) tasks.push(entryTask("STATE_ROOT", entry));
      }
    }
  } else {
    for (const entry of inventory.entries) tasks.push(entryTask(receipt.request.inventoryDirectoryRole, entry));
  }
  if (top.inventoried !== true) {
    frames.push(
      nullRecord([
        ["role", top.role],
        ["parentRole", top.parentRole],
        ["name", top.name],
        ["handle", inventory.directoryHandleSha256],
        ["inventoried", true],
        ["tasks", tasks],
      ]),
    );
    return frames;
  }
  const parentRemaining = [];
  for (const task of top.tasks) parentRemaining.push(task);
  const childTask = parentRemaining.shift();
  if (childTask === undefined) failBinding();
  frames.push(
    nullRecord([
      ["role", top.role],
      ["parentRole", top.parentRole],
      ["name", top.name],
      ["handle", top.handle],
      ["inventoried", true],
      ["tasks", parentRemaining],
    ]),
  );
  frames.push(
    nullRecord([
      ["role", childTask.role],
      ["parentRole", childTask.parentRole],
      ["name", childTask.name],
      ["handle", inventory.directoryHandleSha256],
      ["inventoried", true],
      ["tasks", tasks],
    ]),
  );
  return frames;
}

